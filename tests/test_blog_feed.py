"""Tests for the published Atom 1.0 blog feed at ``docs/blog/feed.xml``.

The feed is regenerated by ``scripts/build_blog_feed.py`` on every sync. These
tests guard the framing of the file, the field set every entry carries and the
ordering rule that keeps the feed deterministic across regenerations.
"""

from __future__ import annotations

import xml.etree.ElementTree as ET
from datetime import datetime, timezone
from pathlib import Path

import pytest

from scripts import build_blog_feed

REPO = Path(__file__).resolve().parents[1]
FEED_PATH = REPO / "docs" / "blog" / "feed.xml"
BLOG_DIR = REPO / "docs" / "blog"
ATOM = "{http://www.w3.org/2005/Atom}"


def _load_feed() -> ET.ElementTree:
    assert FEED_PATH.exists(), f"{FEED_PATH} must exist; run scripts/build_blog_feed.py"
    return ET.parse(FEED_PATH)  # noqa: S314 -- the generator writes the feed


@pytest.fixture(scope="module")
def feed() -> ET.ElementTree:
    return _load_feed()


def _entries(feed: ET.ElementTree) -> list[ET.Element]:
    return feed.getroot().findall(f"{ATOM}entry")


def test_feed_is_valid_atom_xml(feed: ET.ElementTree) -> None:
    root = feed.getroot()
    assert root.tag == f"{ATOM}feed", f"root must be Atom feed, got {root.tag}"
    assert root.find(f"{ATOM}title") is not None, "feed needs a <title>"
    assert root.find(f"{ATOM}id") is not None, "feed needs an <id>"
    assert root.get(f"{{{ATOM}}}lang") or root.get("{http://www.w3.org/XML/1998/namespace}lang") == "en"


def test_feed_links_index_and_self(feed: ET.ElementTree) -> None:
    root = feed.getroot()
    rels: dict[str, str] = {}
    for link in root.findall(f"{ATOM}link"):
        rels[link.get("rel", "alternate")] = link.get("href", "")
    assert rels.get("alternate", "").endswith("/blog/index.html"), rels
    assert rels.get("self", "").endswith("/blog/feed.xml"), rels


def test_feed_contains_every_blog_article_once(feed: ET.ElementTree) -> None:
    expected = {page.name for page in BLOG_DIR.glob("*.html") if page.name != "index.html"}
    canonical_to_page: dict[str, str] = {}
    for page in BLOG_DIR.glob("*.html"):
        if page.name == "index.html":
            continue
        text = page.read_text(encoding="utf-8")
        for line in text.splitlines():
            if 'rel="canonical"' in line:
                canonical_to_page[_extract_href(line)] = page.name
                break
    seen: set[str] = set()
    for entry in _entries(feed):
        entry_id = entry.find(f"{ATOM}id")
        assert entry_id is not None and entry_id.text, "every entry needs an <id>"
        href = entry_id.text.strip()
        assert href in canonical_to_page, f"{href} is not the canonical of any blog page"
        assert href not in seen, f"duplicate entry for {href}"
        seen.add(href)
    missing = expected - {canonical_to_page[href] for href in seen}
    assert not missing, f"feed omits these pages: {sorted(missing)}"


def test_every_entry_carries_required_atom_fields(feed: ET.ElementTree) -> None:
    for entry in _entries(feed):
        title = entry.find(f"{ATOM}title")
        assert title is not None and (title.text or "").strip(), "entry title required"
        assert title.get("{http://www.w3.org/XML/1998/namespace}lang") in {"de", "en"}
        published = entry.find(f"{ATOM}published")
        updated = entry.find(f"{ATOM}updated")
        assert published is not None and published.text, "every entry needs <published>"
        assert updated is not None and updated.text, "every entry needs <updated>"
        _parse_datetime(published.text)
        _parse_datetime(updated.text)
        author = entry.find(f"{ATOM}author")
        assert author is not None and author.find(f"{ATOM}name") is not None, "entry needs <author><name>"
        link = entry.find(f'{ATOM}link[@rel="alternate"]')
        assert link is not None and link.get("href", "").endswith(".html"), "entry needs an alternate link"
        article_link_href = link.get("href")
        id_text = entry.find(f"{ATOM}id").text.strip()
        assert id_text == article_link_href, "id and link href must match"


def test_entries_are_reverse_chronological_by_updated(feed: ET.ElementTree) -> None:
    last_updated = None
    for entry in _entries(feed):
        current = _parse_datetime(entry.find(f"{ATOM}updated").text)
        if last_updated is not None:
            assert current <= last_updated, (
                "feed order must be non-increasing by <updated> across entries"
            )
        last_updated = current


def test_updated_is_not_earlier_than_published(feed: ET.ElementTree) -> None:
    for entry in _entries(feed):
        updated = _parse_datetime(entry.find(f"{ATOM}updated").text)
        published = _parse_datetime(entry.find(f"{ATOM}published").text)
        assert updated >= published, "<updated> must be at or after <published>"


def test_feed_is_deterministic(feed: ET.ElementTree) -> None:
    # Run the generator twice against the public tree and compare bytes.
    rebuilt = build_blog_feed._render_feed(build_blog_feed._parse_entries(BLOG_DIR))
    assert rebuilt == FEED_PATH.read_text(encoding="utf-8"), (
        "feed must be byte-identical to its regenerated form"
    )


def _extract_href(line: str) -> str:
    return line.split('href="', 1)[1].split('"', 1)[0]


def _parse_datetime(text: str) -> datetime:
    cleaned = text.strip().replace("Z", "+00:00")
    parsed = datetime.fromisoformat(cleaned)
    if parsed.tzinfo is None:
        parsed = parsed.replace(tzinfo=timezone.utc)
    return parsed
